// BackendOptions configures the runtime backend.
type BackendOptions struct {
	Image string
	// FIFODir defaults to the fifo directory under StateDir.
	FIFODir string
	// StateDir is the runtime recovery root; it defaults to /var/lib/rheic.
	StateDir string
	Network  runtime.Network
	// Artifacts maps logical names of runtime-shipped binaries, such as
	// containerd-shim-nerdbox-v1, gvproxy, and qemu, to absolute host paths.
	// Create and Start verify every listed artifact before launching it.
	Artifacts map[string]string
	// DigestsPath is the digest file generated by
	// scripts/update-artifact-digests.sh, normally build/digests.yaml.
	DigestsPath string
}

// Backend implements the runtime.Backend contract with ctr.
type Backend struct {
	client   *Client
	image    string
	fifoDir  string
	stateDir string
	network  runtime.Network
	verifier *artifact.Verifier

	skillsMu   sync.Mutex
	skillsPins map[string]*skillsPin
}

type proxyRoute struct {
	service string
	host    string
	port    uint16
}

// CreateWithProxy configures the optional guest helper while preserving the
// stable runtime.Backend contract for consumers pinned to older releases.
func (b *Backend) CreateWithProxy(ctx context.Context, cfg *runtime.Config, helperPath string, guestPort uint16, serviceHost string) (runtime.Handle, error) {
	cfg.ProxyHelperPath = helperPath
	cfg.ProxyGuestPort = guestPort
	cfg.ProxyServiceHost = serviceHost
	return b.Create(ctx, *cfg)
}

// CreateWithProxyRouteArgs configures one helper with multiple service-specific
// guest listeners over the existing per-VM channel.
func (b *Backend) CreateWithProxyRouteArgs(ctx context.Context, cfg *runtime.Config, helperPath string, routeArgs []string) (runtime.Handle, error) {
	routes, err := parseProxyRouteArgs(routeArgs)
	if err != nil {
		return runtime.Handle{}, err
	}
	cfg.ProxyHelperPath = helperPath
	cfg.ProxyGuestPort = 0
	cfg.ProxyServiceHost = ""
	return b.create(ctx, cfg, routes)
}

func parseProxyRouteArgs(values []string) ([]proxyRoute, error) {
	routes := make([]proxyRoute, 0, len(values))
	for _, value := range values {
		service, target, ok := strings.Cut(value, "=")
		if !ok {
			return nil, errors.New("invalid proxy route")
		}
		host, portText, ok := strings.Cut(target, ":")
		if !ok || strings.Contains(portText, ":") {
			return nil, errors.New("invalid proxy route host or port")
		}
		port, err := strconv.ParseUint(portText, 10, 16)
		if err != nil {
			return nil, errors.New("invalid proxy route port")
		}
		routes = append(routes, proxyRoute{service: service, host: host, port: uint16(port)})
	}
	if !validProxyRoutes(routes) {
		return nil, errors.New("proxy routes are invalid")
	}
	return routes, nil
}

var _ runtime.Backend = (*Backend)(nil)

// NewBackend creates a containerd-backed runtime.
func NewBackend(cfg Config, opts BackendOptions) (*Backend, error) {
	client, err := New(cfg)
	if err != nil {
		return nil, err
	}
	var verifier *artifact.Verifier
	if len(opts.Artifacts) > 0 || opts.DigestsPath != "" {
		verifier, err = artifact.NewVerifier(artifact.Config{
			DigestsPath: opts.DigestsPath,
			Artifacts:   opts.Artifacts,
		})
		if err != nil {
			return nil, fmt.Errorf("configure runtime artifact verification: %w", err)
		}
	}
	stateDir := opts.StateDir
	if stateDir == "" {
		stateDir = "/var/lib/rheic"
	}
	fifoDir := defaultIfEmpty(opts.FIFODir, filepath.Join(stateDir, "fifo"))
	return &Backend{
		client:   client,
		image:    opts.Image,
		fifoDir:  fifoDir,
		stateDir: stateDir,
		network:  opts.Network,
		verifier: verifier,
	}, nil
}

// verifyArtifacts hashes the manifest, patches, and runtime-shipped binaries
// before every launch. When the caller configures runtime-managed artifacts the
// policy is mandatory and a mismatch fails closed; a backend built without any
// managed artifact paths runs in explicit host-provided mode and is documented
// as unmanaged instead of being rejected.
func (b *Backend) verifyArtifacts() error {
	if b.verifier == nil {
		return nil
	}
	return b.verifier.Verify()
}

// Capabilities reports the current adapter capabilities.
func (b *Backend) Capabilities(context.Context) (runtime.Capabilities, error) {
	return runtime.Capabilities{
		Workspace: true,
		Network:   b.network != nil,
		Snapshots: false,
		GPU:       false,
		IPv6:      false,
	}, nil
}

// Create creates and starts a detached nerdbox task.
//
//nolint:gocritic // The value signature is required by runtime.Backend.
func (b *Backend) Create(ctx context.Context, cfg runtime.Config) (runtime.Handle, error) {
	return b.create(ctx, &cfg, nil)
}

func defaultIfEmpty(value, fallback string) string {
	if value != "" {
		return value
	}
	return fallback
}

// pullProgressForwarder adapts ctr-adapter pull progress to the runtime
// callback. It returns nil when the caller did not request progress, keeping
// the plain non-streaming pull path.
func pullProgressForwarder(cfg *runtime.Config) func(Progress) {
	if cfg == nil || cfg.OnProgress == nil {
		return nil
	}
	return func(p Progress) {
		cfg.OnProgress(runtime.ProgressUpdate{Phase: p.Phase, Completed: p.Completed, Total: p.Total})
	}
}

//nolint:gocognit,gocyclo,cyclop,funlen // The create transaction keeps failure handling explicit.
func (b *Backend) create(ctx context.Context, cfg *runtime.Config, proxyRoutes []proxyRoute) (runtime.Handle, error) {
	skillsPin, skillsMounts, skillsLabels, err := b.openSkills(cfg)
	if err != nil {
		return runtime.Handle{}, err
	}
	defer closeSkillsPin(&skillsPin)
	if err := b.verifyArtifacts(); err != nil {
		return runtime.Handle{}, err
	}
	image := defaultIfEmpty(cfg.Image, b.image)
	workspaceMounts, err := workspaceMounts(cfg)
	if err != nil {
		return runtime.Handle{}, err
	}
	fifoDir := cfg.FIFODir
	if fifoDir == "" {
		fifoDir = b.fifoDir
	}
	if fifoDir == "" {
		fifoDir = filepath.Join(b.stateDir, "fifo")
	}
	id := ContainerID(cfg.Name)
	exists, err := b.client.containerExists(ctx, id)
	if err != nil {
		return runtime.Handle{}, fmt.Errorf("inspect container: %w", err)
	}
	if exists {
		return runtime.Handle{}, fmt.Errorf("container %s already exists", id)
	}
	opID, _ := ids.FromContext(ctx)
	if ids.Validate(opID) != nil || !strings.HasPrefix(opID, "op_") {
		opID = ""
	}
	w, err := journal.NewWithOpID(b.stateDir, id, opID)
	if err != nil {
		return runtime.Handle{}, fmt.Errorf("start create journal: %w", err)
	}
	if err := b.client.EnsureImageProgress(ctx, image, pullProgressForwarder(cfg)); err != nil {
		return runtime.Handle{}, err
	}
	generation, err := newCreateGeneration()
	if err != nil {
		return runtime.Handle{}, err
	}
	spec := RunSpec{
		ContainerID: id,
		Name:        cfg.Name,
		Image:       image,
		Generation:  generation,
		CPUs:        cfg.CPUs,
		MemoryMiB:   cfg.MemoryMiB,
		FIFODir:     fifoDir,
		Env:         append([]string(nil), cfg.Env...),
		Privileged:  cfg.Privileged,
	}
	if opID != "" {
		spec.Labels = append(spec.Labels, "rheic.op-id="+opID)
	}
	if err := applyProxyConfig(&spec, cfg, proxyRoutes); err != nil {
		return runtime.Handle{}, err
	}
	for _, volume := range cfg.BlockVolumes {
		spec.Mounts = append(spec.Mounts, Mount{Type: "ext4", Source: volume.Source, Destination: volume.Destination})
	}
	spec.Annotations = append(spec.Annotations, workspaceAnnotations(workspaceMounts)...)
	spec.Mounts = append(spec.Mounts, workspaceMounts...)
	if err := applySkillsMounts(&spec, workspaceMounts, skillsMounts, skillsLabels); err != nil {
		return runtime.Handle{}, err
	}
	if err := w.Phase("network"); err != nil {
		return runtime.Handle{}, err
	}
	if b.network != nil {
		if err := w.Track("network", cfg.Name, ""); err != nil {
			return runtime.Handle{}, err
		}
	}
	attachment, err := b.startCreateNetwork(ctx, cfg, w.Token())
	if err != nil {
		return runtime.Handle{}, err
	}
	spec.Annotations = append(append([]string(nil), attachment.Annotations...), spec.Annotations...)
	if err := w.Phase("run"); err != nil {
		if b.network != nil {
			return runtime.Handle{}, errors.Join(err, b.stopNetwork(ctx, cfg.Name))
		}
		return runtime.Handle{}, err
	}
	if err := b.client.Run(ctx, spec); err != nil {
		cleanupErr := b.cleanupFailedCreate(ctx, id, generation)
		if b.network != nil {
			cleanupErr = errors.Join(cleanupErr, b.stopNetwork(ctx, cfg.Name))
		}
		return runtime.Handle{}, errors.Join(err, cleanupErr)
	}
	if err := w.BookkeepAfterRun(generation); err != nil {
		// The container exists but the journal could not be closed; run the
		// same failed-create cleanup rather than leaking a live container.
		cleanupErr := b.cleanupFailedCreate(ctx, id, generation)
		if b.network != nil {
			cleanupErr = errors.Join(cleanupErr, b.stopNetwork(ctx, cfg.Name))
		}
		return runtime.Handle{}, errors.Join(err, cleanupErr)
	}
	b.rememberSkills(id, skillsPin)
	skillsPin = nil
	return runtime.Handle{ID: id, FIFODir: fifoDir}, nil
}

func applySkillsMounts(spec *RunSpec, workspaceMounts, skillsMounts []Mount, labels []string) error {
	if len(skillsMounts) == 0 {
		return nil
	}
	if err := validateReservedMounts(workspaceMounts, []string{runtime.SkillsStoreGuestPath, runtime.SkillsHelperGuestPath}); err != nil {
		return err
	}
	spec.Labels = append(spec.Labels, labels...)
	spec.Mounts = append(spec.Mounts, skillsMounts...)
	return nil
}

func (b *Backend) startCreateNetwork(ctx context.Context, cfg *runtime.Config, token string) (runtime.NetworkAttachment, error) {
	if b.network == nil {
		return runtime.NetworkAttachment{}, nil
	}
	if attester, ok := b.network.(runtime.NetworkAttester); ok {
		return attester.StartOwned(ctx, cfg.Name, token, cfg.Ports, cfg.Allow, cfg.Deny)
	}
	return b.network.Start(ctx, cfg.Name, cfg.Ports, cfg.Allow, cfg.Deny)
}

// workspaceAnnotations marks workspace mounts for the shim's macOS-only
// caller-ownership mode. Linux deliberately stays on libkrun's LinuxComplete
// passthrough, which preserves host UID/GID and xattrs; the annotation is
// ignored there so helper and rootfs mounts never inherit the macOS mode.
func workspaceAnnotations(mounts []Mount) []string {
	annotations := make([]string, 0, len(mounts))
	for _, workspace := range mounts {
		hash := sha256.Sum256([]byte(workspace.Destination))
		annotations = append(annotations, fmt.Sprintf("io.rheic.workspace.%x=true", hash[:]))
	}
	return annotations
}

func workspaceMounts(cfg *runtime.Config) ([]Mount, error) {
	workspaces := cfg.Workspaces
	if len(workspaces) == 0 && cfg.Workspace != "" {
		workspaces = []runtime.Workspace{{Path: cfg.Workspace}}
	}

	mounts := make([]Mount, 0, len(workspaces))
	seen := make(map[string]struct{}, len(workspaces))
	for _, workspace := range workspaces {
		// ctr parses --mount as a comma-delimited key/value string. Never let
		// a host path add mount fields or smuggle control characters into it.
		if !validMountSource(workspace.Path) {
			return nil, errors.New("workspace source must not be empty or contain mount delimiters or control characters")
		}
		destination := workspace.GuestPath
		if destination == "" {
			destination = workspace.Path
		}
		if err := validateGuestWorkspacePath(destination); err != nil {
			return nil, fmt.Errorf("invalid workspace guest path: %w", err)
		}
		if _, exists := seen[destination]; exists {
			return nil, fmt.Errorf("duplicate workspace guest path %q", destination)
		}
		seen[destination] = struct{}{}
		mounts = append(mounts, Mount{
			Source:            workspace.Path,
			Destination:       destination,
			ReadOnly:          workspace.ReadOnly,
			RecursiveReadOnly: workspace.ReadOnly,
		})
	}

	// Workspace mounts must not shadow fixed runtime mounts. This is especially
	// important for the guest proxy helper, which must remain the trusted binary
	// mounted by the runtime.
	reserved := make([]string, 0, len(cfg.BlockVolumes)+1)
	for _, volume := range cfg.BlockVolumes {
		if volume.Destination != "" {
			reserved = append(reserved, volume.Destination)
		}
	}
	if cfg.ProxyHelperPath != "" {
		reserved = append(reserved, "/tmp/rheic-proxy-helper")
	}
	if err := validateReservedMounts(mounts, reserved); err != nil {
		return nil, err
	}
	return mounts, nil
}

func validateReservedMounts(mounts []Mount, reserved []string) error {
	for _, mount := range mounts {
		for _, destination := range reserved {
			if mountPathsOverlap(mount.Destination, destination) {
				return fmt.Errorf("workspace guest path %q overlaps runtime mount %q", mount.Destination, destination)
			}
		}
	}
	return nil
}

func validateGuestWorkspacePath(destination string) error {
	if !path.IsAbs(destination) || path.Clean(destination) != destination || strings.ContainsAny(destination, ",=\x00\r\n") {
		return fmt.Errorf("%q must be a clean absolute guest path without mount delimiters or control characters", destination)
	}
	return nil
}

func mountPathsOverlap(first, second string) bool {
	return first == second || strings.HasPrefix(first, second+"/") || strings.HasPrefix(second, first+"/")
}

func applyProxyConfig(spec *RunSpec, cfg *runtime.Config, routes []proxyRoute) error {
	if err := applyProxyChannel(spec, cfg); err != nil {
		return err
	}
	return applyProxyHelper(spec, cfg, routes)
}

func applyProxyHelper(spec *RunSpec, cfg *runtime.Config, routes []proxyRoute) error {
	if cfg.ProxyHelperPath == "" {
		if cfg.ProxyGuestPort != 0 || cfg.ProxyServiceHost != "" || len(routes) != 0 {
			return errors.New("proxy helper options require a helper binary path")
		}
		return nil
	}
	if err := validateProxyHelperConfig(cfg, routes); err != nil {
		return err
	}
	spec.Mounts = append(spec.Mounts, Mount{
		Source:      cfg.ProxyHelperPath,
		Destination: "/tmp/rheic-proxy-helper",
		ReadOnly:    true,
	})
	// Run the trusted static helper directly as the container process. This
	// keeps proxy-enabled workload images independent of /bin/sh and avoids
	// interpolating configuration into a shell program.
	spec.Args = proxyHelperArgs(cfg, routes)
	spec.RunAsRoot = true
	return nil
}

func validateProxyHelperConfig(cfg *runtime.Config, routes []proxyRoute) error {
	if cfg.ProxyPort < 1027 || cfg.ProxySocket == "" || !filepath.IsAbs(cfg.ProxyHelperPath) || strings.ContainsAny(cfg.ProxyHelperPath, ",=\x00\r\n") {
		return errors.New("proxy helper requires a valid channel and executable path")
	}
	if len(routes) == 0 {
		if cfg.ProxyGuestPort >= 1024 && validProxyServiceHost(cfg.ProxyServiceHost) {
			return nil
		}
		return errors.New("proxy helper requires a valid guest port and service host")
	}
	if cfg.ProxyGuestPort != 0 || cfg.ProxyServiceHost != "" || !validProxyRoutes(routes) {
		return errors.New("proxy helper routes are invalid or conflict with legacy route settings")
	}
	return nil
}

func proxyHelperArgs(cfg *runtime.Config, routes []proxyRoute) []string {
	args := []string{"/tmp/rheic-proxy-helper"}
	if len(routes) == 0 {
		return append(args, "-listen", fmt.Sprintf("127.0.0.1:%d", cfg.ProxyGuestPort),
			"-cid", "2", "-port", fmt.Sprint(cfg.ProxyPort), "-service-host", cfg.ProxyServiceHost)
	}
	args = append(args, "-cid", "2", "-port", fmt.Sprint(cfg.ProxyPort))
	for _, route := range routes {
		args = append(args, "-route", fmt.Sprintf("%s=%s:%d", route.service, route.host, route.port))
	}
	return args
}

func validProxyRoutes(routes []proxyRoute) bool {
	if len(routes) < 2 || len(routes) > 32 {
		return false
	}
	services := make(map[string]struct{}, len(routes))
	ports := make(map[uint16]struct{}, len(routes))
	for _, route := range routes {
		if !validProxyServiceName(route.service) || route.port < 1024 || !validProxyServiceHost(route.host) {
			return false
		}
		if _, exists := services[route.service]; exists {
			return false
		}
		if _, exists := ports[route.port]; exists {
			return false
		}
		services[route.service] = struct{}{}
		ports[route.port] = struct{}{}
	}
	return true
}

func validProxyServiceName(name string) bool {
	if name == "" || len(name) > 64 {
		return false
	}
	for _, char := range name {
		if char < 'a' || char > 'z' {
			if char < '0' || char > '9' {
				if char != '-' {
					return false
				}
			}
		}
	}
	return true
}

func validProxyServiceHost(host string) bool {
	if host == "" || strings.HasPrefix(host, ".") || strings.HasSuffix(host, ".") {
		return false
	}
	for _, char := range host {
		if (char >= 'a' && char <= 'z') || (char >= 'A' && char <= 'Z') ||
			(char >= '0' && char <= '9') || char == '.' || char == '-' {
			continue
		}
		return false
	}
	return true
}

// cleanupFailedCreate removes a container that ctr created before its run
// failed. Without it a partial container keeps the sandbox name reserved and
// every retry fails with "container already exists".
//
// The container id is derived from the sandbox name, so it cannot distinguish
// this attempt from a concurrent create that reused the name. Deletion
// therefore requires the container's generation label to match the generation
// recorded by this attempt. A missing or unreadable generation fails closed
// instead of deleting a container whose owner cannot be established.
func (b *Backend) cleanupFailedCreate(ctx context.Context, id, generation string) error {
	cleanupCtx, cancel := context.WithTimeout(context.WithoutCancel(ctx), 15*time.Second)
	defer cancel()
	exists, err := b.client.containerExists(cleanupCtx, id)
	if err != nil || !exists {
		return err
	}
	if generation == "" {
		return fmt.Errorf("verify container %s ownership after failed create: missing generation", id)
	}
	labels, err := b.client.containerLabels(cleanupCtx, id)
	if err != nil {
		return fmt.Errorf("verify container %s ownership after failed create: %w", id, err)
	}
	observed := labels[generationLabel]
	if observed == "" {
		return fmt.Errorf("verify container %s ownership after failed create: container has no generation label", id)
	}
	if observed != generation {
		// Another create owns this container now; leaving it intact is the
		// only safe outcome.
		return nil
	}
	// A failed run may leave a task behind; ignore its absence.
	_ = b.client.DeleteTask(cleanupCtx, id)
	if err := b.client.DeleteContainer(cleanupCtx, id); err != nil {
		return fmt.Errorf("remove container after failed create: %w", err)
	}
	return nil
}

func newCreateGeneration() (string, error) {
	var token [16]byte
	if _, err := rand.Read(token[:]); err != nil {
		return "", fmt.Errorf("generate sandbox generation: %w", err)
	}
	return fmt.Sprintf("%x", token), nil
}

func applyProxyChannel(spec *RunSpec, cfg *runtime.Config) error {
	annotation, err := proxyChannelAnnotation(cfg)
	if err != nil {
		return err
	}
	if annotation != "" {
		spec.Annotations = append(spec.Annotations, annotation)
	}
	return nil
}

// proxyChannelAnnotation renders the shim annotation for a guest-dialed
// vsock channel or returns an empty string when the channel is disabled.
func proxyChannelAnnotation(cfg *runtime.Config) (string, error) {
	if cfg.ProxyPort == 0 && cfg.ProxySocket == "" {
		return "", nil
	}
	if cfg.ProxyPort < 1027 || cfg.ProxyPort > 65535 || !filepath.IsAbs(cfg.ProxySocket) || len(cfg.ProxySocket) >= 104 || strings.ContainsAny(cfg.ProxySocket, ",=\x00\r\n") {
		return "", errors.New("proxy channel requires a port >= 1027 and a socket path")
	}
	return fmt.Sprintf("io.rheic.proxy=port=%d,socket=%s", cfg.ProxyPort, cfg.ProxySocket), nil
}

// Handle returns the runtime handle for a sandbox name.
func (b *Backend) Handle(name string) runtime.Handle {
	return runtime.Handle{ID: ContainerID(name), FIFODir: b.fifoDir}
}

// Start starts a stopped task.
func (b *Backend) Start(ctx context.Context, h runtime.Handle) error {
	if err := b.verifyArtifacts(); err != nil {
		return err
	}
	if err := b.requireSkillsPin(ctx, h.ID); err != nil {
		return err
	}
	if b.network != nil {
		if _, err := b.network.Start(ctx, strings.TrimPrefix(h.ID, "rheic-"), h.Ports, h.Allow, h.Deny); err != nil {
			return err
		}
	}
	if err := b.client.StartTask(ctx, h.ID, h.FIFODir); err != nil {
		if b.network != nil {
			return errors.Join(err, b.stopNetwork(ctx, strings.TrimPrefix(h.ID, "rheic-")))
		}
		return err
	}
	return nil
}

func (b *Backend) stopNetwork(ctx context.Context, name string) error {
	cleanupCtx, cancel := context.WithTimeout(context.WithoutCancel(ctx), 10*time.Second)
	defer cancel()
	if err := b.network.Stop(cleanupCtx, name); err != nil {
		return fmt.Errorf("stop sandbox network: %w", err)
	}
	return nil
}

// Stop terminates a task.
func (b *Backend) UpdatePolicy(ctx context.Context, h runtime.Handle, allow, deny []runtime.Rule, revision int) error {
	if b.network == nil {
		return errors.New("runtime has no network policy engine")
	}
	return b.network.UpdatePolicy(ctx, strings.TrimPrefix(h.ID, "rheic-"), h.Ports, allow, deny, revision)
}

func (b *Backend) UpdatePorts(ctx context.Context, h runtime.Handle, ports []runtime.Port) error {
	if b.network == nil {
		return errors.New("runtime has no network port engine")
	}
	return b.network.UpdatePorts(ctx, strings.TrimPrefix(h.ID, "rheic-"), ports)
}

// SetGitDaemon delegates the optional clone-mode forward capability to the
// configured network implementation. Unsupported networks fail closed.
func (b *Backend) SetGitDaemon(ctx context.Context, sandbox string, enabled bool) (uint16, error) {
	if b.network == nil {
		return 0, errors.New("runtime has no Git daemon forwarding capability")
	}
	forwarder, ok := b.network.(runtime.GitDaemonForwarder)
	if !ok {
		return 0, errors.New("runtime network does not support Git daemon forwarding")
	}
	return forwarder.SetGitDaemon(ctx, sandbox, enabled)
}

func (b *Backend) Stop(ctx context.Context, h runtime.Handle, grace time.Duration) error {
	if grace <= 0 {
		grace = 5 * time.Second
	}
	err := b.client.StopTask(ctx, h.ID, grace)
	if b.network != nil {
		err = errors.Join(err, b.stopNetwork(ctx, strings.TrimPrefix(h.ID, "rheic-")))
	}
	return err
}

// Delete removes the task and container.
func (b *Backend) Delete(ctx context.Context, h runtime.Handle) error {
	status, err := b.client.taskStatus(ctx, h.ID)
	labels := map[string]string{}
	if err == nil && b.skillsPin(h.ID) == nil {
		labels, _ = b.client.containerLabels(ctx, h.ID)
	}
	if err == nil && status != "" {
		err = b.client.DeleteTask(ctx, h.ID)
	}
	if err == nil {
		var exists bool
		exists, err = b.client.containerExists(ctx, h.ID)
		if err == nil && exists {
			err = b.client.DeleteContainer(ctx, h.ID)
		}
	}
	if b.network != nil {
		err = errors.Join(err, b.stopNetwork(ctx, strings.TrimPrefix(h.ID, "rheic-")))
	}
	if err == nil {
		err = b.forgetSkillsPath(h.ID, labels[skillsPinPathLabel])
	}
	return err
}

func (b *Backend) requireSkillsPin(ctx context.Context, id string) error {
	labels, err := b.client.containerLabels(ctx, id)
	if err != nil {
		return fmt.Errorf("inspect container labels: %w", err)
	}
	if labels[skillsLabel] == "" {
		return nil
	}
	if b.skillsPin(id) != nil {
		return nil
	}
	if err := b.adoptSkillsPin(id, labels); err != nil {
		return fmt.Errorf("reattach shared skills pin: %w", err)
	}
	return nil
}

// ContainerID returns the containerd container id for a sandbox name.
func ContainerID(name string) string { return "rheic-" + name }

// Recover reconciles journal-recorded resources under the backend state
// root: filesystem entries via marker proof, network attachments via the
// optional NetworkAttester, and containers via the generation label. Every
// branch that cannot prove ownership LEAVES the resource and reports a
// typed finding; nothing is deleted speculatively.
func (b *Backend) Recover(ctx context.Context) ([]journal.Finding, error) {
	if err := ctx.Err(); err != nil {
		return nil, err
	}
	attester, _ := b.network.(runtime.NetworkAttester)
	return journal.RecoverWith(b.stateDir, time.Now, func(rec journal.Record, res journal.Resource) (bool, journal.Reason, error) {
		switch res.Kind {
		case "network":
			return b.recoverNetwork(ctx, attester, rec, res)
		case "container":
			return b.recoverContainer(ctx, rec, res)
		default:
			return false, journal.UnsupportedOwnership, nil
		}
	})
}

func (b *Backend) recoverNetwork(ctx context.Context, attester runtime.NetworkAttester, rec journal.Record, res journal.Resource) (bool, journal.Reason, error) {
	if attester == nil || b.network == nil {
		return false, journal.UnsupportedOwnership, nil
	}
	state, err := attester.AttachmentState(ctx, res.NativeID, rec.Token)
	switch {
	case errors.Is(err, runtime.ErrOwnershipUnsupported):
		return false, journal.UnsupportedOwnership, nil
	case err != nil:
		return false, "", err
	case state == runtime.AttachmentAbsent:
		// create() cleanup (or the host) already removed the gateway: the
		// journal entry is stale and the resource is provably gone.
		return true, "", nil
	case state == runtime.AttachmentForeign:
		return false, journal.ForeignResource, nil
	}
	if err := b.network.Stop(ctx, res.NativeID); err != nil {
		return false, "", err
	}
	return true, "", nil
}

func (b *Backend) recoverContainer(ctx context.Context, rec journal.Record, res journal.Resource) (bool, journal.Reason, error) {
	if res.NativeID == "" {
		return false, journal.UnsupportedOwnership, nil
	}
	exists, err := b.client.containerExists(ctx, rec.ID)
	if err != nil {
		return false, "", err
	}
	if !exists {
		return true, "", nil
	}
	labels, err := b.client.containerLabels(ctx, rec.ID)
	if err != nil {
		return false, "", err
	}
	if labels[generationLabel] != res.NativeID {
		// Another create attempt owns the container now.
		return false, journal.ForeignResource, nil
	}
	// A live task may or may not exist; mirror cleanupFailedCreate, which
	// ignores task-delete absence and only surfaces container-delete errors.
	_ = b.client.DeleteTask(ctx, rec.ID)
	if err := b.client.DeleteContainer(ctx, rec.ID); err != nil {
		return false, "", err
	}
	return true, "", nil
}
